/* Bake colour-free, rounded wedge bevel masks. Nothing is rasterised during gestures. */
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
// Only the upper wedge is baked. The renderer rotates this same mask five times.
const width = 384;
const height = 256;
const levels = 64;
const stops = [0, 10, 20, 35, 65, 100];
const dark = [0.95, 0.56, 0, 0, 0, 0];
const light = [0, 0, 0.48, 0.82, 0.14, 0];
const rays = Array.from({ length: 5 }, (_, i) => {
  const angle = ((i + 0.5) * Math.PI * 2) / 5;
  return [Math.sin(angle), -Math.cos(angle)];
});
const pixels = [Buffer.alloc(width * height), Buffer.alloc(width * height)];
for (let y = 0; y < height; y++) {
  for (let x = 0; x < width; x++) {
    const px = 200 + ((x + 0.5) * 600) / width - 500,
      py = ((y + 0.5) * 400) / height - 500,
      radius = Math.hypot(px, py);
    if (radius < 140 || radius > 500 || Math.abs(Math.atan2(px, -py)) > Math.PI / 5) continue;
    const circle = Math.min(radius - 140, 500 - radius);
    let side = Infinity;
    for (const [ux, uy] of rays)
      if (px * ux + py * uy > 0) side = Math.min(side, Math.abs(px * uy - py * ux));
    // Smooth intersection joins each radial edge to its inner and outer arcs.
    const h = Math.max(72 - Math.abs(circle - side), 0) / 72;
    const distance = Math.max(0, Math.min(circle, side) - (h * h * 72) / 4);
    if (distance >= 100) continue;
    let band = 0;
    while (distance > stops[band + 1]) band++;
    const t = (distance - stops[band]) / (stops[band + 1] - stops[band]);
    const a = dark[band] + (dark[band + 1] - dark[band]) * t;
    const b = light[band] + (light[band + 1] - light[band]) * t;
    // Compensate the lower layer for source-over compositing of the light layer.
    pixels[0][y * width + x] = Math.round((a / (1 - b)) * (levels - 1));
    pixels[1][y * width + x] = Math.round(b * (levels - 1));
  }
}
function crc32(buffer) {
  let crc = 0xffffffff;
  for (const byte of buffer) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (crc & 1 ? 0xedb88320 : 0);
  }
  return (crc ^ 0xffffffff) >>> 0;
}
function chunk(name, data) {
  const type = Buffer.from(name),
    size = Buffer.alloc(4),
    crc = Buffer.alloc(4);
  size.writeUInt32BE(data.length);
  crc.writeUInt32BE(crc32(Buffer.concat([type, data])));
  return Buffer.concat([size, type, data, crc]);
}
function png(alpha) {
  const header = Buffer.alloc(13);
  header.writeUInt32BE(width, 0);
  header.writeUInt32BE(height, 4);
  header[8] = 8;
  header[9] = 3; // White indexed alpha mask; all colour comes from site CSS tokens.
  const scan = Buffer.alloc(height * (width + 1));
  for (let y = 0; y < height; y++) {
    alpha.copy(scan, y * (width + 1) + 1, y * width, (y + 1) * width);
  }
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk('IHDR', header),
    chunk('PLTE', Buffer.alloc(levels * 3, 255)),
    chunk(
      'tRNS',
      Buffer.from(Array.from({ length: levels }, (_, i) => Math.round((i * 255) / (levels - 1)))),
    ),
    chunk('IDAT', zlib.deflateSync(scan, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}
const value =
  '/* Generated by tools/runtime-build/build-guide-pressure.cjs; alpha only, no palette. */\n' +
  '// prettier-ignore\n' +
  'window.TDBTreatmentGuidePressureMasks = Object.freeze(' +
  JSON.stringify(
    Object.fromEntries(
      ['dark', 'light'].map((key, i) => [
        key,
        'data:image/png;base64,' + png(pixels[i]).toString('base64'),
      ]),
    ),
  ) +
  ');\n';
const target = path.resolve(__dirname, '../../src/treatment-guide/pressure-masks.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== value)
    throw Error('Guide pressure masks are stale; run tools/runtime-build/build-guide-pressure.cjs');
} else fs.writeFileSync(target, value);
console.log(
  `Guide pressure masks ${process.argv.includes('--check') ? 'verified' : 'written'} (${Buffer.byteLength(value)} bytes)`,
);
