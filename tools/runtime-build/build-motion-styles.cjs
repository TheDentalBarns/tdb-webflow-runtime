/* Rebuild the CSS side of the same release as the JS motion profile. */
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '../..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const check = process.argv.includes('--check');
function emit(file, value) {
  if (check) {
    if (read(file) !== value) throw Error(file + ' is stale; run npm run build');
  } else fs.writeFileSync(path.join(root, file), value);
}
const profile = require('./motion-profile.cjs').css();
emit('src/styles/tdb-motion-profile.css', profile);
// Share the existing composition manifest with the Python compatibility entry.
const manifest = read('tools/build-ui.py');
function sources(name) {
  return [
    ...manifest.match(new RegExp(name + ' = \\[([\\s\\S]*?)\\]'))[1].matchAll(/'([^']+)'/g),
  ].map((m) => m[1]);
}
const globalHeader =
  '/* TDB global UI stylesheet, loaded early from the Webflow head.\n * Generated by tools/build-ui.py - edit source modules, not this file.\n * Shared coordination, scrolling, feedback, consent and compatibility. Other feature CSS has independent readiness.\n */\n\n';
const global =
  globalHeader +
  sources('GLOBAL_SOURCES')
    .map((file) => read(file).trim())
    .join('\n\n') +
  '\n';
const critical =
  '/* Generated critical UI: inline before the asynchronous global stylesheet. */\n' +
  sources('CRITICAL_SOURCES')
    .map((file) => read(file).trim())
    .join('\n\n') +
  '\n';
emit('src/styles/tdb-ui.css', global);
emit('src/styles/tdb-ui-critical.css', critical);
emit(
  'dist/tdb-vip.css',
  '/* TDB VIP drawer stylesheet.\n * Generated by tools/build-ui.py - loaded with the VIP runtime.\n */\n\n' +
    sources('VIP_SOURCES')
      .map((file) => read(file).trim())
      .join('\n\n') +
    '\n',
);
// Preserve modern @starting-style syntax unsupported by the old CSS minifier.
emit('dist/tdb-calculator.css', read('src/styles/tdb-calculator.css'));
execFileSync(
  process.execPath,
  [path.join(__dirname, 'minify-ui.cjs'), ...(check ? ['--check'] : [])],
  { stdio: 'inherit' },
);
